/**
 * Screen size breakpoints
 *
 * PURPOSE:
 * - Define constants for mobile, tablet, desktop layouts
 * - Centralized, easy to change for future devices
 */
class Breakpoints {
  static const double mobile = 600;  // width < 600px
  static const double tablet = 1024; // width >= 600px && < 1024px
  static const double desktop = 1440; // width >= 1024px
}